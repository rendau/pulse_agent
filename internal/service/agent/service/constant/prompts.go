// FormatKnown — формат поддерживается.
func FormatKnown(format string) bool {
	_, ok := formatRules[format]
	return ok
}

// SystemPrompt — системный промпт: общие правила, список навыков, instructions pulse, оформление под формат
// (пустой — telegram; clientSchema — схема системы-клиента) и правило графиков, если клиент
// их принимает.
func SystemPrompt(pulseInstructions, skills, format string, clientSchema, charts bool) string {
	prompt := systemPrompt
	if skills != "" {
		prompt += skillsHeader + skills
	}
	if pulseInstructions != "" {
		prompt += pulseInstructionsHeader + pulseInstructions
	}

	rules, ok := formatRules[format]
	if !ok {
		rules = formatRules[FormatTelegram]
	}
	if clientSchema {
		rules = clientSchemaRules
	}
	prompt += "\n\nОформление ответа:\n" + rules
	if charts {
		prompt += "\n" + chartRule
	}
	return prompt
}

